suppressMessages({library(apcluster); library(cluster)})
x <- scale(iris[,1:4]); S <- negDistMat(x, r=2)
a <- apcluster(S, q=0, seed=1234); k <- length(a@exemplars)
cat("slots:", paste(slotNames(a), collapse=","), "\n")
cat("k=",k," dpsim=",a@dpsim," netsim=",a@netsim," expref=",a@expref,"\n")
D <- as.dist(-S); p <- pam(D, k=k, diss=TRUE)
cost_ap <- sum(-S[cbind(1:150, a@idx)]); cost_pam <- sum(-S[cbind(1:150, p$id.med[p$clustering])])
cat("cout p-mediane AP=",cost_ap," pam=",cost_pam,"\n")
t <- system.time(for(i in 1:20) apcluster(S, seed=i))[3]/20; cat("temps AP moyen (s)", t, "\n")
